// Link previews for deep links. WhatsApp, LinkedIn, Facebook, Slack and X fetch a shared
// address without running JavaScript and read its Open Graph tags. A post's address
// (/2026/11/some-post) has no file of its own on GitHub Pages, so crawlers got the site's
// 404 hand-over and showed a bare card. This writes a tiny page at every published post's
// path (<year>/<month>/<slug>/index.html) carrying the blog's share card, and a redirect
// that sends real readers into the app exactly as the 404 hand-over does. It runs from
// .github/workflows/share-pages.yml every half hour with a service-account key; the site
// sync then publishes the pages with the rest of the app.
//
//   node tools/share-pages.mjs                 reads published posts (FIREBASE_SERVICE_ACCOUNT, a JSON key)
//   node tools/share-pages.mjs posts.json      renders the posts in a JSON file instead (local check)
import {readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://www.stouras.com/ucd-blog';
const MARK = '<!-- generated by tools/share-pages.mjs; do not edit -->';

// The month a post files under, as the app computes it (util.js monthKey), in Irish time.
export const pathOf = p => {
  const d = new Date(p.publishedAt || p.createdAt);
  const parts = new Intl.DateTimeFormat('en-IE', {timeZone: 'Europe/Dublin', year: 'numeric', month: '2-digit'}).formatToParts(d);
  const y = parts.find(x => x.type === 'year').value, m = parts.find(x => x.type === 'month').value;
  return `${y}/${m}/${p.slug}`;
};

// The page itself: the blog's card (the same tags as index.html) and the hand-over.
export function render(p) {
  const path = pathOf(p), here = `${SITE}/${path}`;
  return `<!doctype html>
<html lang="en">
<head>
${MARK}
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>UCD blog</title>
<meta name="description" content="Blog posts by UCD students on how organisations face the megatrends shaping business and society.">
<meta name="robots" content="noindex">
<link rel="canonical" href="${here}">
<meta property="og:type" content="article">
<meta property="og:site_name" content="UCD blog">
<meta property="og:locale" content="en_IE">
<meta property="og:title" content="UCD blog — Posts by curious UCD students">
<meta property="og:description" content="Blog posts by UCD students on how organisations face the megatrends shaping business and society.">
<meta property="og:url" content="${here}">
<meta property="og:image" content="${SITE}/og-image.jpg">
<meta property="og:image:secure_url" content="${SITE}/og-image.jpg">
<meta property="og:image:type" content="image/jpeg">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="UCD blog — Posts by curious UCD students">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="UCD blog — Posts by curious UCD students">
<meta name="twitter:description" content="Blog posts by UCD students on how organisations face the megatrends shaping business and society.">
<meta name="twitter:image" content="${SITE}/og-image.jpg">
<meta name="twitter:image:alt" content="UCD blog — Posts by curious UCD students">
<link rel="icon" href="../../../favicon.ico" sizes="any">
<script>
  // Hand the address to the app, as the site's 404 page does for addresses without a file:
  // the app root is three segments up (<root>/<year>/<month>/<slug>/), wherever the app is mounted.
  var p = location.pathname.replace(/\\/?$/, '/'), root = p.replace(/\\d{4}\\/\\d{2}\\/[^/]+\\/$/, '');
  location.replace(root + '?redirect=' + encodeURIComponent(p.slice(0, -1) + location.search + location.hash) + '&_=' + Date.now());
</script>
<noscript><meta http-equiv="refresh" content="0; url=${SITE}/?redirect=${encodeURIComponent('/ucd-blog/' + path)}"></noscript>
</head>
<body><p>Opening the post… <a href="${SITE}/?redirect=${encodeURIComponent('/ucd-blog/' + path)}">Continue to the UCD blog</a>.</p></body>
</html>
`;
}

// Replaces the generated pages with one per published post; returns what changed.
export function writePages(posts, root = ROOT) {
  const wanted = new Map(posts.filter(p => p.status === 'published' && /^[a-z0-9-]+$/.test(p.slug || '')).map(p => [pathOf(p), render(p)]));
  const removed = [];
  for (const y of readdirSync(root).filter(n => /^\d{4}$/.test(n))) for (const m of readdirSync(join(root, y)).filter(n => /^\d{2}$/.test(n))) for (const s of readdirSync(join(root, y, m))) {
    const f = join(root, y, m, s, 'index.html');
    if (existsSync(f) && readFileSync(f, 'utf8').includes(MARK) && !wanted.has(`${y}/${m}/${s}`)) { rmSync(join(root, y, m, s), {recursive: true}); removed.push(`${y}/${m}/${s}`); }
  }
  const written = [];
  for (const [path, html] of wanted) {
    const f = join(root, path, 'index.html');
    if (existsSync(f) && readFileSync(f, 'utf8') === html) continue;
    mkdirSync(dirname(f), {recursive: true}); writeFileSync(f, html); written.push(path);
  }
  return {written, removed, total: wanted.size};
}

async function publishedPosts() {
  const key = process.env.FIREBASE_SERVICE_ACCOUNT;
  if (!key) throw Error('Set FIREBASE_SERVICE_ACCOUNT to the service-account JSON, or pass a posts.json file.');
  const admin = await import('firebase-admin');
  const app = admin.default.initializeApp({credential: admin.default.credential.cert(JSON.parse(key))});
  const snap = await app.firestore().collection('posts').where('status', '==', 'published').select('slug', 'status', 'publishedAt', 'createdAt').get();
  return snap.docs.map(d => d.data());
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const posts = process.argv[2] ? JSON.parse(readFileSync(process.argv[2], 'utf8')) : await publishedPosts();
  const r = writePages(posts);
  console.log(`${r.total} published post${r.total === 1 ? '' : 's'}: ${r.written.length} page${r.written.length === 1 ? '' : 's'} written, ${r.removed.length} removed.`);
  for (const p of r.written) console.log('  + ' + p); for (const p of r.removed) console.log('  - ' + p);
  process.exit(0);
}
