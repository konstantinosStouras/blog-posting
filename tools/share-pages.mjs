// Link previews for deep links. WhatsApp, LinkedIn, Facebook, Slack and X fetch a shared
// address without running JavaScript and read its Open Graph tags. A post's address
// (/project-management/2026/11/some-post) or a blog's (/project-management) has no file of
// its own on GitHub Pages, so crawlers got the site's root 404 page and showed its card,
// which belongs to another app. This writes a tiny page at every blog's path
// (<blog>/index.html) and every published post's (<blog>/<year>/<month>/<slug>/index.html,
// or <year>/<month>/<slug>/ for a post with no blog) carrying the blog's share card with the
// post's or blog's title, and a redirect that sends real readers into the app exactly as the
// 404 hand-over does. It runs from .github/workflows/share-pages.yml every half hour with a
// service-account key; the site sync then publishes the pages with the rest of the app.
//
//   node tools/share-pages.mjs                 reads the blogs and published posts (FIREBASE_SERVICE_ACCOUNT, a JSON key)
//   node tools/share-pages.mjs data.json       renders {blogs, posts} from a JSON file instead (local check)
import {readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://www.stouras.com/ucd-blog';
const MARK = '<!-- generated by tools/share-pages.mjs; do not edit -->';
const NAME = /^[a-z0-9][a-z0-9-]{0,79}$/;   // a blog's url-name (backend saveBlog) or a post's slug (util.js slugify)
const DESCRIPTION = 'Blog posts by UCD students on how organisations face the megatrends shaping business and society.';
const esc = s => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// The month a post files under, as the app computes it (util.js monthKey), in Irish time,
// under its blog's name when it has one (util.js postPath).
export const pathOf = p => {
  const d = new Date(p.publishedAt || p.createdAt);
  const parts = new Intl.DateTimeFormat('en-IE', {timeZone: 'Europe/Dublin', year: 'numeric', month: '2-digit'}).formatToParts(d);
  const y = parts.find(x => x.type === 'year').value, m = parts.find(x => x.type === 'month').value;
  return `${p.blogId ? p.blogId + '/' : ''}${y}/${m}/${p.slug}`;
};

// The page at a path: the blog's card (the same tags as index.html, headed with the post's
// or blog's title) and the hand-over to the app.
export function render(path, {title = '', description = ''} = {}) {
  const here = `${SITE}/${path}`, depth = path.split('/').length, up = '../'.repeat(depth), post = depth > 1;
  const heading = title ? `${title} — UCD blog` : 'UCD blog — Posts by curious UCD students';
  const blurb = description || DESCRIPTION;
  return `<!doctype html>
<html lang="en">
<head>
${MARK}
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(heading)}</title>
<meta name="description" content="${esc(blurb)}">
<meta name="robots" content="noindex">
<link rel="canonical" href="${here}">
<meta property="og:type" content="${post ? 'article' : 'website'}">
<meta property="og:site_name" content="UCD blog">
<meta property="og:locale" content="en_IE">
<meta property="og:title" content="${esc(heading)}">
<meta property="og:description" content="${esc(blurb)}">
<meta property="og:url" content="${here}">
<meta property="og:image" content="${SITE}/og-image.jpg">
<meta property="og:image:secure_url" content="${SITE}/og-image.jpg">
<meta property="og:image:type" content="image/jpeg">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="UCD blog — Posts by curious UCD students">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${esc(heading)}">
<meta name="twitter:description" content="${esc(blurb)}">
<meta name="twitter:image" content="${SITE}/og-image.jpg">
<meta name="twitter:image:alt" content="UCD blog — Posts by curious UCD students">
<link rel="icon" href="${up}favicon.ico?v=2" sizes="any">
<script>
  // Hand the address to the app, as the site's 404 page does for addresses without a file:
  // the app root is ${depth} segment${depth === 1 ? '' : 's'} up from this page, wherever the app is mounted.
  var p = location.pathname.replace(/\\/?$/, '/'), root = p.split('/').slice(0, -${depth + 1}).join('/') + '/';
  location.replace(root + '?redirect=' + encodeURIComponent(p.slice(0, -1) + location.search + location.hash));
</script>
<noscript><meta http-equiv="refresh" content="0; url=${SITE}/?redirect=${encodeURIComponent('/ucd-blog/' + path)}"></noscript>
</head>
<body><p>Opening the ${post ? 'post' : 'blog'}… <a href="${SITE}/?redirect=${encodeURIComponent('/ucd-blog/' + path)}">Continue to the UCD blog</a>.</p></body>
</html>
`;
}

// Every page wanted: one per blog, one per published post with a usable address.
export function pages({blogs = [], posts = []} = {}) {
  const wanted = new Map();
  for (const b of blogs) if (NAME.test(b.id || '')) wanted.set(b.id, render(b.id, {title: b.title, description: b.description}));
  for (const p of posts) if (p.status === 'published' && NAME.test(p.slug || '') && (!p.blogId || NAME.test(p.blogId))) wanted.set(pathOf(p), render(pathOf(p), {title: p.title}));
  return wanted;
}

// Replaces the generated pages with the wanted ones; returns what changed. Only pages
// carrying MARK are ever removed, so a hand-written file under the same layout is kept.
export function writePages(data, root = ROOT) {
  const wanted = pages(data), removed = [], written = [];
  const dirs = d => { try { return readdirSync(d, {withFileTypes: true}).filter(e => e.isDirectory()).map(e => e.name); } catch { return []; } };
  const ours = f => existsSync(f) && readFileSync(f, 'utf8').includes(MARK);
  const prune = d => { try { if (!readdirSync(d).length) { rmSync(d, {recursive: true}); return true; } } catch {} return false; };
  const isYear = n => /^\d{4}$/.test(n), isMonth = n => /^\d{2}$/.test(n);
  for (const top of dirs(root).filter(n => !n.startsWith('.') && n !== 'node_modules')) {
    const blog = !isYear(top), prefix = blog ? top + '/' : '';
    if (blog && ours(join(root, top, 'index.html')) && !wanted.has(top)) { rmSync(join(root, top, 'index.html')); removed.push(top); }
    for (const y of blog ? dirs(join(root, top)).filter(isYear) : [top]) {
      for (const m of dirs(join(root, prefix + y)).filter(isMonth)) {
        for (const s of dirs(join(root, prefix + y, m))) {
          const path = `${prefix}${y}/${m}/${s}`;
          if (ours(join(root, path, 'index.html')) && !wanted.has(path)) { rmSync(join(root, path), {recursive: true}); removed.push(path); }
        }
        prune(join(root, prefix + y, m));
      }
      prune(join(root, prefix + y));
    }
    if (blog) prune(join(root, top));
  }
  for (const [path, html] of wanted) {
    const f = join(root, path, 'index.html');
    if (existsSync(f) && readFileSync(f, 'utf8') === html) continue;
    mkdirSync(dirname(f), {recursive: true}); writeFileSync(f, html); written.push(path);
  }
  return {written, removed, total: wanted.size};
}

// The blogs and the published posts, from Firestore with a service-account key.
async function load() {
  const key = process.env.FIREBASE_SERVICE_ACCOUNT;
  if (!key) throw Error('Set FIREBASE_SERVICE_ACCOUNT to the service-account JSON, or pass a data.json file ({blogs, posts}).');
  const {initializeApp, cert} = await import('firebase-admin/app');
  const {getFirestore} = await import('firebase-admin/firestore');
  const db = getFirestore(initializeApp({credential: cert(JSON.parse(key))}));
  const [blogs, posts] = await Promise.all([
    db.collection('blogs').select('title', 'description').get(),
    db.collection('posts').where('status', '==', 'published').select('slug', 'status', 'publishedAt', 'createdAt', 'blogId', 'title').get(),
  ]);
  return {blogs: blogs.docs.map(d => ({id: d.id, ...d.data()})), posts: posts.docs.map(d => d.data())};
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const data = process.argv[2] ? JSON.parse(readFileSync(process.argv[2], 'utf8')) : await load();
  const r = writePages(data);
  console.log(`${r.total} page${r.total === 1 ? '' : 's'} wanted: ${r.written.length} written, ${r.removed.length} removed.`);
  for (const p of r.written) console.log('  + ' + p); for (const p of r.removed) console.log('  - ' + p);
  process.exit(0);
}
