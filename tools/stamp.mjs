// Cache stamp. GitHub Pages lets a browser keep every file for ten minutes, and the
// site has no build step, so after a deploy a browser could run a module it fetched
// fresh against one it still held from before. index.html therefore names every
// module and the stylesheet with ?v=<stamp>, where the stamp is a hash of their
// contents: when anything changes, every address changes with it, and a page that
// loads the new index.html loads only new files. An import map turns each module's
// plain import ("./util.js") into the stamped address, so the modules themselves
// never mention the stamp.
//
//   node tools/stamp.mjs          rewrite index.html from the files in the working tree
//   node tools/stamp.mjs --index  from the files staged for commit (the pre-commit hook)
//   node tools/stamp.mjs --check  exit 1 if index.html does not carry the stamp of the working tree
import {readFileSync, writeFileSync, readdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BEGIN = '<!-- cache-stamp: generated by tools/stamp.mjs (npm run stamp); do not edit by hand -->';
const END = '<!-- /cache-stamp -->';
const mode = process.argv[2] || '';
const git = (...args) => execFileSync('git', args, {cwd: ROOT, encoding: 'utf8'});

// The files a page loads: every module in the app root and the stylesheet. Tests, tools,
// the share pages and node_modules live elsewhere.
function sources() {
  if (mode === '--index') {
    const staged = git('ls-files', '--cached', '--', '*.js', 'styles.css').split(/\r?\n/).filter(f => f && !f.includes('/'));
    return Object.fromEntries(staged.sort().map(f => [f, git('show', ':' + f)]));
  }
  const files = readdirSync(ROOT).filter(f => f.endsWith('.js') || f === 'styles.css').sort();
  return Object.fromEntries(files.map(f => [f, readFileSync(join(ROOT, f), 'utf8')]));
}
// Line endings do not count: the same text checked out as LF or CRLF gives the same stamp.
export const stampOf = files => createHash('sha256').update(Object.entries(files).map(([f, s]) => f + '\n' + s.replace(/\r\n/g, '\n')).join('\n')).digest('hex').slice(0, 10);

// The stamped block (the import map, the stylesheet and the module preloads), the
// app.js script tag and nothing else.
export function stamp(html, files) {
  const v = stampOf(files), nl = html.includes('\r\n') ? '\r\n' : '\n';
  const modules = Object.keys(files).filter(f => f.endsWith('.js'));
  const map = JSON.stringify({imports: Object.fromEntries(modules.map(m => ['./' + m, `./${m}?v=${v}`]))});
  const block = [BEGIN, `<script type="importmap">${map}</script>`, `<link rel="stylesheet" href="styles.css?v=${v}">`,
    ...modules.filter(m => m !== 'app.js').map(m => `<link rel="modulepreload" href="${m}?v=${v}">`), END].join(nl);
  const a = html.indexOf(BEGIN), b = html.indexOf(END);
  if (a < 0 || b < 0) throw Error('index.html has no cache-stamp block');
  html = html.slice(0, a) + block + html.slice(b + END.length);
  html = html.replace(/<script type="module" src="app\.js(?:\?v=[0-9a-f]+)?">/, `<script type="module" src="app.js?v=${v}">`);
  return {html, v};
}

const files = sources(), page = join(ROOT, 'index.html');
if (mode === '--index') {
  // Stamp the copy being committed, whatever is or is not staged of index.html itself,
  // and the working copy too when it has no edits of its own waiting.
  const staged = git('show', ':index.html'), {html, v} = stamp(staged, files);
  let clean = true; try { git('diff', '--quiet', '--', 'index.html'); } catch { clean = false; }
  if (html !== staged) {
    const blob = execFileSync('git', ['hash-object', '-w', '--stdin'], {cwd: ROOT, input: html, encoding: 'utf8'}).trim();
    git('update-index', '--cacheinfo', `100644,${blob},index.html`);
  }
  if (clean) writeFileSync(page, html);
  console.log('cache stamp', v);
} else {
  const before = readFileSync(page, 'utf8'), {html, v} = stamp(before, files);
  if (mode === '--check') { if (html !== before) { console.error(`index.html is not stamped for the current files (expected ${v}); run: npm run stamp`); process.exit(1); } }
  else if (html !== before) writeFileSync(page, html);
  console.log('cache stamp', v, html === before ? '(unchanged)' : '(index.html updated)');
}
