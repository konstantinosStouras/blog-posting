// Peer review of blogs (study guide section 5.3, "Others' blog assessment"): after the
// deadline each student is assigned the posts of four classmates, grades each from 1 to
// 10 with a paragraph of constructive feedback, and the admin aggregates the four reviews
// (with the AI review, when there is one) into the feedback the author receives and a
// score for each reviewer. Pure functions (no DOM, no network, no database) so the
// assignment, its checks and the prompts run in `npm test`.
//
// The assignment is the one the grading spreadsheet made by hand for years: the students
// with a published post are shuffled (a seed makes the draw reproducible) and arranged
// in a circle; each reviews the posts of the next PER_STUDENT students round the circle.
// That gives, with no searching: nobody reviews their own post (an offset is never zero),
// nobody gets the same post twice (the offsets are distinct), every post receives exactly
// PER_STUDENT reviews and every reviewer gives exactly PER_STUDENT. The spreadsheet's
// "uniques = 5" column is verifyAssignments(), run on every row.
import {htmlToText, fill, clampGrade} from './ai-grading-model.js';

export const PER_STUDENT = 4;
export const GRADE_MIN = 1, GRADE_MAX = 10;          // the guide: "rate your blogs assigned from 1 to 10"
export const MIN_WORDS = 50, MAX_CHARS = 4000;       // "a short paragraph of constructive feedback"
export const reviewId = (moduleId, postId, reviewerUid) => `${moduleId}_${postId}_${reviewerUid}`;

