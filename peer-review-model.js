// ---------- a reproducible shuffle ----------
// A string seed becomes a 32-bit state (FNV-1a) for a small PRNG (mulberry32); the same
// seed always gives the same order, so a round can be redrawn or audited later.
function seedState(seed) { let h = 2166136261; for (const c of String(seed)) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619); } return h >>> 0; }
export function seededRandom(seed) {
  let a = seedState(seed);
  return () => { a = (a + 0x6D2B79F5) >>> 0; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}
export function seededShuffle(items, seed) {
  const out = [...items], rnd = seededRandom(seed);
  for (let i = out.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [out[i], out[j]] = [out[j], out[i]]; }
  return out;
}
export const newSeed = () => Math.random().toString(36).slice(2, 10) + Date.now().toString(36);

// One post per author: the latest published one. Posts that are not published are left out.
export function reviewablePosts(posts) {
  const latest = new Map();
  for (const p of posts) { if (p.status !== 'published' || !p.authorId) continue; const cur = latest.get(p.authorId); if (!cur || (p.publishedAt || 0) > (cur.publishedAt || 0)) latest.set(p.authorId, p); }
  return [...latest.values()];
}

// The draw. `posts`: the module's posts; `extraReviewers`: uids of students with no post
// who should still review (optional; each takes `perStudent` posts from those with the
// fewest reviews, so a few posts get a fifth). Returns the assignments (postId, authorId,
// reviewerUid, order 1..n), the circle, and who was left out and why.
export function assignPeerReviews({posts = [], extraReviewers = [], perStudent = PER_STUDENT, seed = newSeed()} = {}) {
  const pool = reviewablePosts(posts);
  if (pool.length < perStudent + 1) throw Error(`At least ${perStudent + 1} students with a published post are needed for ${perStudent} reviews each; this module has ${pool.length}.`);
  const circle = seededShuffle(pool, seed), n = circle.length, assignments = [];
  circle.forEach((mine, i) => { for (let k = 1; k <= perStudent; k++) { const target = circle[(i + k) % n]; assignments.push({postId: target.id, authorId: target.authorId, reviewerUid: mine.authorId, order: k}); } });
  const extras = [...new Set(extraReviewers)].filter(uid => !pool.some(p => p.authorId === uid));
  for (const uid of extras) assignments.push(...pickForReviewer(uid, pool, assignments, perStudent));
  return {assignments, seed, circle: circle.map(p => ({postId: p.id, authorId: p.authorId})), extras, posts: pool};
}
// `perStudent` posts for one reviewer: not their own, not one they already have, the
// posts with the fewest reviews first (ties broken by the circle order).
function pickForReviewer(uid, pool, assignments, perStudent) {
  const count = postId => assignments.filter(a => a.postId === postId).length;
  const have = new Set(assignments.filter(a => a.reviewerUid === uid).map(a => a.postId));
  const candidates = pool.filter(p => p.authorId !== uid && !have.has(p.id)).map((p, i) => ({p, i, n: count(p.id)})).sort((a, b) => a.n - b.n || a.i - b.i);
  return candidates.slice(0, perStudent).map(({p}, k) => ({postId: p.id, authorId: p.authorId, reviewerUid: uid, order: have.size + k + 1}));
}
// After the draw: a post published late gets `perStudent` reviewers from those with the
// fewest assignments, and a student who joined late gets `perStudent` posts. Returns only
// the new assignments.
export function fillGaps({assignments = [], posts = [], reviewers = [], perStudent = PER_STUDENT} = {}) {
  const pool = reviewablePosts(posts), all = [...assignments], added = [];
  const load = uid => all.filter(a => a.reviewerUid === uid).length;
  for (const p of pool) {
    const missing = perStudent - all.filter(a => a.postId === p.id).length; if (missing <= 0) continue;
    const have = new Set(all.filter(a => a.postId === p.id).map(a => a.reviewerUid));
    const pick = reviewers.filter(uid => uid !== p.authorId && !have.has(uid)).map((uid, i) => ({uid, i, n: load(uid)})).sort((a, b) => a.n - b.n || a.i - b.i).slice(0, missing);
    for (const {uid} of pick) { const a = {postId: p.id, authorId: p.authorId, reviewerUid: uid, order: load(uid) + 1}; all.push(a); added.push(a); }
  }
  for (const uid of reviewers) {
    const missing = perStudent - load(uid); if (missing <= 0) continue;
    const picked = pickForReviewer(uid, pool, all, missing); all.push(...picked); added.push(...picked);
  }
  return added;
}

// The spreadsheet's check, on every row: each reviewer has `perStudent` distinct posts and
// none their own; each post has `perStudent` distinct reviewers (more is allowed, fewer is not).
export function verifyAssignments(assignments, {perStudent = PER_STUDENT, posts = null} = {}) {
  const problems = [], byReviewer = new Map(), byPost = new Map();
  for (const a of assignments) {
    (byReviewer.get(a.reviewerUid) || byReviewer.set(a.reviewerUid, []).get(a.reviewerUid)).push(a);
    (byPost.get(a.postId) || byPost.set(a.postId, []).get(a.postId)).push(a);
    if (a.reviewerUid === a.authorId) problems.push(`Reviewer ${a.reviewerUid} is assigned their own post.`);
  }
  for (const [uid, rows] of byReviewer) {
    const ids = new Set(rows.map(a => a.postId));
    if (ids.size !== rows.length) problems.push(`Reviewer ${uid} has the same post more than once.`);
    if (rows.length < perStudent) problems.push(`Reviewer ${uid} has ${rows.length} post${rows.length === 1 ? '' : 's'} instead of ${perStudent}.`);
  }
  for (const [postId, rows] of byPost) {
    const ids = new Set(rows.map(a => a.reviewerUid));
    if (ids.size !== rows.length) problems.push(`Post ${postId} has the same reviewer more than once.`);
    if (rows.length < perStudent) problems.push(`Post ${postId} has ${rows.length} reviewer${rows.length === 1 ? '' : 's'} instead of ${perStudent}.`);
  }
  if (posts) for (const p of reviewablePosts(posts)) if (!byPost.has(p.id)) problems.push(`Post ${p.id} has no reviewers.`);
  return {ok: !problems.length, problems, reviewers: byReviewer.size, posts: byPost.size, assignments: assignments.length};
}

// ---------- the reviewer's submission ----------
export const words = s => String(s || '').trim().split(/\s+/).filter(Boolean).length;
export function validateReview({grade, assessment}) {
  const g = clampGrade(grade);
  if (g == null || g < GRADE_MIN) throw Error(`Give a rating from ${GRADE_MIN} to ${GRADE_MAX}.`);
  if (Math.round(g * 2) !== g * 2) throw Error('Ratings go in halves: 7, 7.5, 8…');
  const a = String(assessment || '').trim();
  if (words(a) < MIN_WORDS) throw Error(`Write at least ${MIN_WORDS} words of feedback (you have ${words(a)}).`);
  if (a.length > MAX_CHARS) throw Error(`Keep the feedback under ${MAX_CHARS} characters.`);
  return {grade: g, assessment: a};
}
// A round takes submissions while it is open and, if it names a deadline, until the end of that day.
export const roundOpen = (round, now = Date.now()) => !!round && round.status === 'open' && (!round.deadline || now <= new Date(round.deadline + 'T23:59:59').getTime());

// ---------- aggregation ----------
const mean = xs => xs.length ? xs.reduce((s, x) => s + x, 0) / xs.length : null;
const round1 = v => v == null ? null : Math.round(v * 100) / 100;
// One row per post: the grades and feedback it received, the raw mean, a leniency-adjusted
// mean (each grade less its reviewer's own average across their reviews, plus the class
// mean, so one harsh or generous grader moves the average less) and the spread, flagged
// when the four disagree by three points or more. `reviews` are the assignment documents,
// with grade and assessment filled in once submitted.
export function peerPostRows({reviews = [], posts = [], users = [], aiReviews = [], summaries = []} = {}) {
  const who = new Map(users.map(u => [u.uid, u])), ai = new Map(aiReviews.map(r => [r.postId, r])), released = new Map(summaries.map(s => [s.postId, s]));
  const submitted = reviews.filter(r => r.grade != null);
  const reviewerMean = new Map(); for (const r of submitted) (reviewerMean.get(r.reviewerUid) || reviewerMean.set(r.reviewerUid, []).get(r.reviewerUid)).push(r.grade);
  for (const [uid, gs] of reviewerMean) reviewerMean.set(uid, mean(gs));
  const classMean = mean(submitted.map(r => r.grade));
  const byPost = new Map(); for (const r of reviews) (byPost.get(r.postId) || byPost.set(r.postId, []).get(r.postId)).push(r);
  return [...byPost.entries()].map(([postId, rows]) => {
    const p = posts.find(x => x.id === postId) || {id: postId}, u = who.get(p.authorId || rows[0].authorId) || {}, got = rows.filter(r => r.grade != null).sort((a, b) => (a.submittedAt || 0) - (b.submittedAt || 0));
    const grades = got.map(r => r.grade), adjusted = got.map(r => r.grade - (reviewerMean.get(r.reviewerUid) ?? classMean) + classMean);
    const spread = grades.length ? Math.max(...grades) - Math.min(...grades) : null, a = ai.get(postId);
    return {postId, authorId: p.authorId || rows[0].authorId, title: p.title || '', url: '', post: p, studentId: u.studentId || '', firstName: u.firstName || '', lastName: u.lastName || '', email: u.contactEmail || u.email || '', penName: p.authorName || u.penName || '',
      assigned: rows.length, received: got.length, grades, reviews: got, pending: rows.filter(r => r.grade == null),
      mean: round1(mean(grades)), adjustedMean: round1(mean(adjusted)), spread, flagged: spread != null && spread >= 3,
      aiGrade: a?.grade ?? null, aiFeedback: a?.feedback || '', synthesis: a?.peerSynthesis || '', suggestedGrade: a?.peerSuggestedGrade ?? null, synthesisAt: a?.peerSynthesisAt || null, synthesisModel: a?.peerSynthesisModel || '',
      finalGrade: a?.finalGrade ?? '', finalFeedback: a?.finalFeedback || '', released: released.get(postId) || null};
  }).sort((a, b) => (a.lastName + a.firstName + a.penName).localeCompare(b.lastName + b.firstName + b.penName));
}
// One row per reviewer: their assigned posts in order, what they submitted, and the admin's
// and the AI's view of their reviewing (the 10% component).
export function peerReviewerRows({reviews = [], posts = [], users = [], notes = []} = {}) {
  const who = new Map(users.map(u => [u.uid, u])), byUid = new Map(), noted = new Map(notes.map(n => [n.reviewerUid, n]));
  for (const r of reviews) (byUid.get(r.reviewerUid) || byUid.set(r.reviewerUid, []).get(r.reviewerUid)).push(r);
  return [...byUid.entries()].map(([uid, rows]) => {
    const u = who.get(uid) || {}, items = rows.sort((a, b) => (a.order || 0) - (b.order || 0)).map(r => ({...r, post: posts.find(p => p.id === r.postId) || {id: r.postId, title: ''}}));
    const done = items.filter(r => r.grade != null), n = noted.get(uid) || null;
    return {reviewerUid: uid, studentId: u.studentId || '', firstName: u.firstName || '', lastName: u.lastName || '', email: u.contactEmail || u.email || '', penName: u.penName || rows[0].reviewerName || '',
      assigned: items.length, done: done.length, items, meanGiven: round1(mean(done.map(r => r.grade))), wordsWritten: done.reduce((s, r) => s + words(r.assessment), 0), lastSubmittedAt: Math.max(0, ...done.map(r => r.submittedAt || 0)) || null,
      aiScore: n?.aiScore ?? null, aiNote: n?.aiNote || '', aiScoredAt: n?.aiScoredAt || null, aiModel: n?.aiModel || '', grade: n?.grade ?? '', note: n?.note || '', releasedAt: n?.releasedAt || null, notes: n};
  }).sort((a, b) => (a.lastName + a.firstName + a.penName).localeCompare(b.lastName + b.firstName + b.penName));
}
