export const PEER_PLACEHOLDERS = ['{brief}', '{blogTitle}', '{module}', '{academicYear}', '{count}', '{mean}', '{adjustedMean}', '{title}', '{penName}'];
export const SYNTHESIS_SCHEMA = {type: 'object', properties: {grade: {type: 'number'}, summary: {type: 'string'}, feedback: {type: 'string'}}, required: ['grade', 'summary', 'feedback'], additionalProperties: false};
export const REVIEWER_SCHEMA = {type: 'object', properties: {score: {type: 'number'}, feedback: {type: 'string'}, perReview: {type: 'array', items: {type: 'object', properties: {score: {type: 'number'}, note: {type: 'string'}}, required: ['score', 'note'], additionalProperties: false}}}, required: ['score', 'feedback', 'perReview'], additionalProperties: false};
const fmt = v => v == null ? 'not available' : Number(v).toFixed(1);
export function buildSynthesis({prompts = DEFAULT_PEER_PROMPTS, persona = '', row, post, blog = {}, module = {}, includePost = true}) {
  if (!row.reviews.length) throw Error('No peer reviews have been submitted for this post yet.');
  const vars = {brief: htmlToText(blog.brief || '') || 'No brief has been written for this blog.', blogTitle: blog.title || '', module: [module.code, module.title].filter(Boolean).join(' '), academicYear: post.academicYear || module.academicYear || '', count: row.reviews.length, mean: fmt(row.mean), adjustedMean: fmt(row.adjustedMean), title: post.title || '', penName: post.authorName || ''};
  const peers = row.reviews.map((r, i) => `Review ${i + 1} (rating ${r.grade}/10):\n${r.assessment}`).join('\n\n');
  const ai = row.aiFeedback ? `\n\nMy own AI review (grade ${fmt(row.aiGrade)}/10):\n"""\n${row.aiFeedback}\n"""` : '';
  const text = includePost ? htmlToText(post.body || '') : '';
  const user = `${fill(prompts.synthesis || DEFAULT_PEER_PROMPTS.synthesis, vars)}\n\nReply with a single JSON object and nothing else: {"grade": <number 0-10>, "summary": "<one or two sentences>", "feedback": "<one paragraph>"}.\n\nPeer reviews:\n"""\n${peers}\n"""${ai}${text ? `\n\nThe blog post, titled "${vars.title}":\n"""\n${text}\n"""` : ''}`;
  return {system: fill(persona, vars), user, schema: SYNTHESIS_SCHEMA};
}
export function buildReviewerAssessment({prompts = DEFAULT_PEER_PROMPTS, persona = '', row, blog = {}, module = {}, postText = () => ''}) {
  const done = row.items.filter(r => r.grade != null);
  if (!done.length) throw Error('This student has not submitted any review yet.');
  const vars = {brief: htmlToText(blog.brief || ''), blogTitle: blog.title || '', module: [module.code, module.title].filter(Boolean).join(' '), academicYear: module.academicYear || '', count: done.length, mean: fmt(row.meanGiven), adjustedMean: '', title: '', penName: row.penName};
  const body = done.map((r, i) => { const t = postText(r.post); return `Review ${i + 1} of the post "${r.post.title || r.postId}" (rating given: ${r.grade}/10):\n"""\n${r.assessment}\n"""${t ? `\nThe post reviewed, abridged:\n"""\n${t.slice(0, 2500)}\n"""` : ''}`; }).join('\n\n');
  const user = `${fill(prompts.reviewer || DEFAULT_PEER_PROMPTS.reviewer, vars)}\n\nReply with a single JSON object and nothing else: {"score": <number 0-10>, "feedback": "<one paragraph>", "perReview": [{"score": <number 0-10>, "note": "<a few words>"}, …]}.\n\nThe student's reviews:\n\n${body}`;
  return {system: fill(persona, vars), user, schema: REVIEWER_SCHEMA};
}
function jsonIn(text) {
  const raw = String(text || '').trim();
  for (const c of [raw, raw.replace(/^```(?:json)?\s*|\s*```$/g, ''), raw.slice(raw.indexOf('{'), raw.lastIndexOf('}') + 1)]) { if (c && c[0] === '{') try { return JSON.parse(c); } catch {} }
  return null;
}
export function parseSynthesis(text) { const o = jsonIn(text); return o ? {grade: clampGrade(o.grade), summary: String(o.summary || '').trim(), feedback: String(o.feedback || '').trim(), raw: String(text).trim()} : {grade: null, summary: '', feedback: String(text || '').trim(), raw: String(text || '').trim()}; }
export function parseReviewerAssessment(text) {
  const o = jsonIn(text);
  if (!o) return {score: null, feedback: String(text || '').trim(), perReview: [], raw: String(text || '').trim()};
  return {score: clampGrade(o.score), feedback: String(o.feedback || '').trim(), perReview: Array.isArray(o.perReview) ? o.perReview.map(x => ({score: clampGrade(x?.score), note: String(x?.note || '').trim().slice(0, 300)})) : [], raw: String(text).trim()};
}
